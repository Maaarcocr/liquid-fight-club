# Generates src/casemap.inc: Unicode case mapping tables (simple mappings as
# compressed runs plus multi-character special cases). The data comes from the
# Unicode case mappings as exposed by Ruby's String#upcase/#downcase/#capitalize
# (the reference behaviour), with no locale-specific rules.
#   ruby tests/gen_casemap.rb > src/casemap.inc
def build(meth)
  simple = []
  special = []
  (0..0x10FFFF).each do |cp|
    next if (0xD800..0xDFFF).cover?(cp)
    ch = [cp].pack("U")
    m = ch.send(meth)
    next if m == ch
    cps = m.codepoints
    if cps.size == 1 then simple << [cp, cps[0] - cp]
    else special << [cp, m]
    end
  end
  runs = []
  simple.each do |cp, d|
    r = runs.last
    if r && r[3] == d && r[2] == 0 && cp == r[1] + 1 && (r[1] - r[0]).zero?
      r[1] = cp; r[2] = 1
    elsif r && r[3] == d && r[2] == 1 && cp == r[1] + 1
      r[1] = cp
    elsif r && r[3] == d && (r[2] == 2 || r[0] == r[1]) && cp == r[1] + 2
      r[1] = cp; r[2] = 2
    else
      runs << [cp, cp, 0, d]
    end
  end
  [runs, special]
end

def c_str(s)
  '"' + s.bytes.map { |b| format("\\x%02x", b) }.join + '"'
end

puts "/* Generated by tests/gen_casemap.rb - do not edit. */"
{ "upper" => :upcase, "lower" => :downcase, "title" => :capitalize }.each do |name, meth|
  runs, special = build(meth)
  puts "static const lq_case_run CASE_#{name.upcase}_RUNS[] = {"
  runs.each { |a, b, stride, d| puts "    {0x#{a.to_s(16)}, 0x#{b.to_s(16)}, #{stride == 0 ? 1 : stride}, #{d}}," }
  puts "};"
  puts "static const lq_case_special CASE_#{name.upcase}_SPECIAL[] = {"
  special.each { |cp, s| puts "    {0x#{cp.to_s(16)}, #{c_str(s)}}," }
  puts "    {0, \"\"}"
  puts "};"
end
