# Generates src/printable.inc: ranges of code points (>= 0x80) that Ruby's
# String#inspect escapes as \u.... (non-printable per the Unicode data
# Ruby uses).
#   ruby tests/gen_printable.rb > src/printable.inc
ranges = []
(0x80..0x10FFFF).each do |cp|
  next if (0xD800..0xDFFF).cover?(cp)
  ch = [cp].pack("U")
  next if ch.inspect == "\"#{ch}\""
  if ranges.last && ranges.last[1] == cp - 1 then ranges.last[1] = cp
  elsif ranges.last && ranges.last[1] == 0xD7FF && cp == 0xE000 then ranges.last[1] = cp
  else ranges << [cp, cp]
  end
end
puts "/* Generated by tests/gen_printable.rb - do not edit. */"
puts "static const int32_t INSPECT_ESCAPED[][2] = {"
ranges.each { |a, b| puts "    {0x#{a.to_s(16)}, 0x#{b.to_s(16)}}," }
puts "};"
